#!/usr/bin/env python3
"""Builds the paper theme for PROOF from proof.css.

Reads every rule, finds colours that only work on a dark ground, and writes the
same selector again with the paper/ink equivalent. The output is appended after
the original rules, so it wins by order with identical specificity.
Run: python3 scripts/paper-theme.py   (rewrites the block after the PAPER marker)
"""
import re, sys, pathlib
P = pathlib.Path(__file__).resolve().parent.parent / "src/app/proof.css"
MARK = "/* ==== PAPER THEME (generated by scripts/paper-theme.py, do not edit by hand) ==== */"
src = P.read_text(encoding="utf-8").split(MARK)[0].rstrip() + "\n"
INK, SOFT, PAPER, CARD, MG = "#0B0B0C", "#55554F", "#F6F6F2", "#FFFFFF", "#D01E98"
COL = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)")
def parse(c):
    c = c.strip().lower()
    if c.startswith("#"):
        h = c[1:]
        if len(h) in (3, 4): h = "".join(x * 2 for x in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    n = [x for x in re.split(r"[,\s/]+", c[c.index("(") + 1:-1]) if x]
    f = [float(x.rstrip("%")) for x in n]
    return int(f[0]), int(f[1]), int(f[2]), (f[3] if len(f) > 3 else 1.0)
def lum(r, g, b): return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255
def is_mg(r, g, b): return r > 150 and b > 90 and g < r * 0.62 and (r - g) > 70
def ink(a, floor=0.0):
    a = max(a, floor)
    return INK if a >= .99 else f"rgba(11,11,12,{a:.2f})".rstrip("0").rstrip(".")
FG = ("color", "fill", "stroke", "-webkit-text-fill-color", "caret-color", "text-decoration-color", "outline-color", "outline", "text-decoration")
def conv(prop, val, rule_has_mg_bg):
    is_fg = prop in FG
    is_border = prop.startswith("border") or prop == "box-shadow"
    is_bg = prop.startswith("background")
    changed = [False]
    def one(m):
        tok = m.group(0)
        try: r, g, b, a = parse(tok)
        except Exception: return tok
        L = lum(r, g, b)
        if is_mg(r, g, b):
            if L > .5 and (is_fg or is_border):          # pale pink made for dark grounds
                changed[0] = True; return MG if a >= .99 else f"rgba(208,30,152,{a:.2f})"
            if is_bg and L < .28:                           # deep magenta-black panels
                changed[0] = True; return "rgba(208,30,152,.07)"
            return tok
        if is_fg:
            if rule_has_mg_bg: return tok                   # white on a magenta button stays
            if L > .55:
                changed[0] = True
                if a < .99: return ink(a, .55)
                return SOFT if L < .86 else INK
            return tok
        if is_border:
            if L > .55:
                changed[0] = True; return ink(a if a < .99 else 1, .3)
            if L < .45 and a >= .99 and prop != "box-shadow":
                changed[0] = True; return INK
            return tok
        if is_bg:
            if L < .3:
                changed[0] = True
                if a < .99: return f"rgba(246,246,242,{min(a + .25, .96):.2f})"
                return PAPER if L < .085 else CARD if L < .16 else "#E6E6E0"
            if L > .8 and a < .5:
                changed[0] = True; return f"rgba(11,11,12,{a:.2f})"
            return tok
        return tok
    out = COL.sub(one, val)
    return out if changed[0] else None
def blocks(text):
    """Yield (prelude, body, depth_preludes) for leaf rules."""
    i, n, stack, buf = 0, len(text), [], ""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == "{":
            stack.append(buf.strip()); buf = ""
        elif ch == "}":
            pre = stack.pop() if stack else ""
            if pre and not pre.startswith("@") and "{" not in buf:
                yield pre, buf, list(stack)
            buf = ""
        else:
            buf += ch
        i += 1
out = []
for sel, body, ctx in blocks(src):
    if any(c.startswith("@keyframes") or c.startswith("@font-face") for c in ctx): continue
    decls = [d.strip() for d in re.split(r";(?![^(]*\))", body) if ":" in d]
    kv = [(d.split(":", 1)[0].strip().lower(), d.split(":", 1)[1].strip()) for d in decls]
    has_mg = any(k.startswith("background") and (re.search(r"var\(--(tbtx|red|blue)\)", v) or any(is_mg(*parse(t)[:3]) and lum(*parse(t)[:3]) > .28 and parse(t)[3] > .6 for t in COL.findall(v))) for k, v in kv)
    new = []
    black_bg = any(k.startswith("background") and "var(--ink)" in v for k, v in kv)
    keeps_black = black_bg or re.search(r"px-btn|px-option\.is-selected|px-kicker b|px-foot-label|px-plus|px-progress", sel)
    for k, v in kv:
        if k.startswith("--"): continue
        imp = " !important" if "!important" in v else ""
        # paper-coloured text and rules were written for black surfaces; on paper they become ink
        if "var(--paper" in v and not keeps_black and not has_mg and (k in FG or k.startswith("border")):
            new.append(f"{k}: {re.sub(r'var\(--paper(-2)?\)', INK, v.replace('!important','').strip())}{imp}")
            continue
        nv = conv(k, v.replace("!important", "").strip(), has_mg)
        if nv: new.append(f"{k}: {nv}{imp}")
    if new:
        rule = f"{sel} {{ {'; '.join(new)}; }}"
        for c in reversed(ctx): rule = f"{c} {{ {rule} }}"
        out.append(rule)
hand = (pathlib.Path(__file__).resolve().parent / "paper-hand.css").read_text(encoding="utf-8")
P.write_text(src + "\n" + MARK + "\n" + "\n".join(out) + "\n" + hand, encoding="utf-8")
print("rules converted:", len(out))
